"""Rebuilds elements.json: mendeleev data + Italian/English texts in tools/testi.
Ricostruisce elements.json: dati di mendeleev + testi italiani/inglesi in tools/testi.

Usage / Uso (from the project root / dalla cartella principale):
    pip install mendeleev
    python tools/build.py
"""
import json, os, runpy

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
LANGS = ('it', 'en')


def load(name):
    with open(os.path.join(HERE, 'testi', name), encoding='utf-8') as f:
        return json.load(f)


runpy.run_path(os.path.join(HERE, 'extract.py'))
with open(os.path.join(HERE, 'data.json'), encoding='utf-8') as f:
    data = json.load(f)

texts, found, captions = {}, {}, {}
for lang in LANGS:
    rows = []
    for i in (1, 2, 3, 4):
        rows += load(f'{lang}{i}.json')
    assert [r[0] for r in rows] == list(range(1, 119)), f'{lang}: texts must cover elements 1-118 in order'
    texts[lang] = rows
    found[lang] = {}
    for i in (1, 2, 3):
        found[lang].update(load(f'cont_{lang}{i}.json'))
    captions[lang] = load(f'didascalie_{lang}.json')
credits = load('crediti_foto.json')

LAB = {'it': ["🔬", "Solo in laboratorio", "pochi atomi creati negli acceleratori di particelle, che durano frazioni di secondo"],
       'en': ["🔬", "Only in the laboratory", "a few atoms made in particle accelerators, lasting fractions of a second"]}
SAMPLE = {'it': 'Campione di {}', 'en': 'Sample of {}'}

# per language (tx.it / tx.en): n name, w discoverers, l place, o name origin, st story,
# dv where it is found, us uses, cu fun fact, ct «found in» list, pc photo caption
for idx, e in enumerate(data):
    z = e['z']
    for k in ('yr', 'who', 'loc', 'en'):
        e.pop(k, None)
    assert texts['it'][idx][2] == texts['en'][idx][2], f'year mismatch for {z}'
    e['y'] = texts['it'][idx][2]
    e['img'] = os.path.exists(os.path.join(ROOT, 'img', f'{z}.jpg'))
    if e['img']:
        e['cr'] = credits[str(z)]
    e['tx'] = {}
    for lang in LANGS:
        t = texts[lang][idx]
        d = dict(n=t[1], w=t[3], l=t[4], o=t[5], st=t[6], dv=t[7], us=t[8], cu=t[9])
        d['ct'] = found[lang].get(str(z)) or [LAB[lang]]
        if e['img']:
            d['pc'] = captions[lang].get(str(z), SAMPLE[lang].format(t[1].lower() if lang == 'it' else t[1].lower()))
        e['tx'][lang] = d
    assert len(e['tx']['it']['ct']) == len(e['tx']['en']['ct']), f'«found in» mismatch for {z}'

with open(os.path.join(ROOT, 'elements.json'), 'w', encoding='utf-8') as f:
    json.dump(data, f, separators=(',', ':'), ensure_ascii=False)
os.remove(os.path.join(HERE, 'data.json'))

# photo credits table / tabella dei crediti delle foto
LIC = {'CC BY 3.0': '[CC BY 3.0](https://creativecommons.org/licenses/by/3.0/)',
       'CC BY-SA 3.0': '[CC BY-SA 3.0](https://creativecommons.org/licenses/by-sa/3.0/)',
       'PD': 'Public domain / Pubblico dominio'}
lines = ['# Photo credits / Crediti delle foto', '',
         'Generated by `tools/build.py`. Changes: small copies (max 480 px) re-encoded as JPEG (quality 80); no other edits. See also `CREDITS.md`.',
         'Generato da `tools/build.py`. Modifiche: copie ridotte (max 480 px) ricompresse in JPEG (qualità 80); nessun\'altra modifica. Vedi anche `CREDITS.md`.', '',
         '| File | Element | Author / Holder | License | Source |', '|---|---|---|---|---|']
for e in data:
    if not e['img']:
        continue
    c = e['cr']
    note = f" — {c['note']}" if c.get('note') else ''
    lines.append(f"| `{e['z']}.jpg` | {e['z']} {e['tx']['en']['n']} | {c['a']} | {LIC[c['l']]}{note} | {c['src']} |")
missing = [str(e['z']) for e in data if not e['img']]
lines += ['', 'No photo / Nessuna foto: ' + ', '.join(missing) + '.', '']
with open(os.path.join(ROOT, 'img', 'CREDITS.md'), 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines))
print('elements.json + img/CREDITS.md updated')
